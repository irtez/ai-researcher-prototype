#!/usr/bin/env python3
"""Generate .claude/agents/<name>.md files from holosophos/holosophos/prompts/<name>.yaml.

Canonical source: holosophos/holosophos/prompts/*.yaml (canon + claude_code sections).
Output: .claude/agents/*.md with YAML frontmatter + body.

The Claude Code entry points (`scripts/run_research.py`,
`scripts/run_eval_claude_code.py`) call `ensure_synced()` at startup, so the
generated files are kept fresh automatically — there is no manual step. The
.md files are gitignored; this script is the only writer.

Run directly to (re)generate from the shell:
    python scripts/sync_claude_agents.py
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any, Dict, Optional

import yaml

PROJECT_DIR = Path(__file__).resolve().parent.parent
PROMPTS_DIR = PROJECT_DIR / "holosophos" / "holosophos" / "prompts"
AGENTS_DIR = PROJECT_DIR / ".claude" / "agents"

# Prompts that must never become a `.claude/agents/*.md`.
#
# system.yaml is the manager — not a Claude Code sub-agent.
#
# The four critic/planner prompts are RUNNER-OWNED: `run_research.py` invokes
# them out of band and writes their briefs itself. Emitting them here would put
# them in `options.agents`, and the manager could then invoke the critics that
# audit it, or write their briefs — which is the one property the design cannot
# lose (spec G6, docs/plans/2026-08-18-self-improving-loop-verification.md).
# `check_orphans()` below is what notices if one leaks in anyway.
SKIP = {
    "system.yaml",
    "session_title.yaml",
    "codearkt_framework.yaml",
    "analysis_critic.yaml",
    "paper_critic.yaml",
    "sufficiency.yaml",
    "planner.yaml",
}

# The `dev-` prefix in .claude/agents/ is RESERVED for hand-written
# developer-harness agents (committed; see .gitignore). This script only ever
# writes the known YAML-derived names below, so it never overwrites or deletes
# a dev-*.md file — but do not add a `dev-*.yaml` prompt source, or generation
# would collide with a committed dev agent. run_research.py filters dev-* out of
# the research manager's agent set (see iter_research_agent_paths there).

# Map YAML stem to Claude Code agent slug (kebab-case for SDK compatibility).
NAME_OVERRIDES = {
    "mle_solver": "mle-solver",
    "mle_solver_remote": "mle-solver-remote",
}

# `MLE_SOLVER_IS_REMOTE` is the same env knob CodeArkt uses (see
# holosophos/holosophos/settings.py). It is read here as a string so this
# script can stay independent of pydantic. Three states:
#   * unset / empty → render BOTH mle-solver and mle-solver-remote (default)
#   * truthy ("true", "1", "yes", "on") → render only mle-solver-remote
#   * falsy ("false", "0", "no", "off") → render only mle-solver
# Use case: launch parallel research sessions with different shell env so the
# heavy session sees only the remote solver and the light session sees only
# the local one — no contention for each other's resources.
_TRUTHY = {"true", "1", "yes", "on"}
_FALSY = {"false", "0", "no", "off"}


def _is_remote_filter() -> Optional[bool]:
    raw = os.environ.get("MLE_SOLVER_IS_REMOTE", "").strip().lower()
    if not raw:
        return None
    if raw in _TRUTHY:
        return True
    if raw in _FALSY:
        return False
    return None  # invalid value → fall back to default (both)


BANNER = (
    "<!-- AUTOGENERATED from holosophos/holosophos/prompts/{src} — "
    "do NOT edit by hand; .claude/agents/ is gitignored and regenerated "
    "from YAML on every run. -->\n"
)


def render_frontmatter(name: str, canon: Dict[str, Any], cc: Dict[str, Any]) -> str:
    """Build the YAML frontmatter block for a Claude Code agent .md file."""
    fm: Dict[str, Any] = {
        "name": name,
        "description": cc.get("description") or canon.get("description") or name,
    }
    for key in ("model", "maxTurns", "effort", "mcpServers", "tools", "disallowedTools"):
        if key in cc:
            fm[key] = cc[key]
    body = yaml.safe_dump(fm, sort_keys=False, default_flow_style=False).strip()
    return f"---\n{body}\n---\n"


def render_body(canon: Dict[str, Any], cc: Dict[str, Any]) -> str:
    """Build the agent .md body from canon + claude_code.prompt_extras."""
    parts = [
        canon.get("role", ""),
        canon.get("guidelines", ""),
        canon.get("output_format", ""),
        cc.get("prompt_extras", ""),
    ]
    body = "\n\n".join(p.strip() for p in parts if p and p.strip()) + "\n"
    # Native Read runs from a session directory, not the source checkout.
    prefix = "holosophos/holosophos/skills/"
    if prefix in body:
        body = body.replace(prefix, str(PROJECT_DIR / prefix) + "/")
        body += (
            f"\nSource project directory: {PROJECT_DIR}. "
            f"Paths inside skill registries beginning with {prefix} are relative "
            "to this source project directory, not the session directory. "
            "Other relative registry paths are relative to the registry's own directory. "
            "Read these reference files in place; save research outputs in the session directory.\n"
        )
    return body


def render_one(yaml_path: Path) -> tuple[Path, str]:
    """Render the expected .md content for one prompt yaml. Returns (out_path, content)."""
    data = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))
    canon = data.get("canon") or {}
    cc = data.get("claude_code") or {}

    stem = yaml_path.stem
    md_name = NAME_OVERRIDES.get(stem, stem)
    out_path = AGENTS_DIR / f"{md_name}.md"

    frontmatter = render_frontmatter(md_name, canon, cc)
    banner = BANNER.format(src=yaml_path.name)
    body = render_body(canon, cc)
    return out_path, frontmatter + banner + "\n" + body


def iter_prompt_yamls() -> list[Path]:
    paths = [p for p in sorted(PROMPTS_DIR.glob("*.yaml")) if p.name not in SKIP]

    is_remote = _is_remote_filter()
    if is_remote is True:
        # Heavy session — only the remote solver should be visible to the manager.
        paths = [p for p in paths if p.stem != "mle_solver"]
    elif is_remote is False:
        # Light session — only the local solver should be visible.
        paths = [p for p in paths if p.stem != "mle_solver_remote"]
    # is_remote is None → keep both (default).
    return paths


def all_prompt_yamls() -> list[Path]:
    """Every non-SKIP prompt YAML, ignoring the ``MLE_SOLVER_IS_REMOTE`` filter.

    That filter is a runtime choice about which solver the manager should see,
    not a statement that the other variant's .md must not exist — so the orphan
    scan below ignores it and stays env-independent.
    """
    return [p for p in sorted(PROMPTS_DIR.glob("*.yaml")) if p.name not in SKIP]


def check_orphans() -> list[tuple[Path, str]]:
    """Agent .md files the manager would load that no non-SKIP YAML accounts for.

    ``--check`` alone cannot catch this: ``find_drift()`` iterates
    ``iter_prompt_yamls()``, which filters ``SKIP`` *before* comparing, so a
    hand-placed ``analysis_critic.md`` is invisible to it — and then gets loaded
    by ``run_research.py::load_all_agents()`` and handed to the manager.

    The filter here mirrors ``run_research.py::iter_research_agent_paths()``
    (everything in ``.claude/agents/`` except the ``dev-`` prefix). It is
    duplicated rather than imported because importing ``run_research`` runs
    ``load_dotenv`` and mutates the environment, which a hygiene check must not
    do; ``tests/test_critic_agent_isolation.py`` asserts the two agree.

    Since ``.claude/`` is gitignored this is a local-dev sensor, not a CI gate —
    the durable guard is that same test.
    """
    expected = {NAME_OVERRIDES.get(p.stem, p.stem) for p in all_prompt_yamls()}
    runner_owned = {NAME_OVERRIDES.get(Path(n).stem, Path(n).stem) for n in SKIP}
    orphans: list[tuple[Path, str]] = []
    for path in sorted(AGENTS_DIR.glob("*.md")):
        if path.stem.startswith("dev-") or path.stem in expected:
            continue
        reason = (
            "runner-owned prompt — must never reach the manager's agent set"
            if path.stem in runner_owned
            else "no prompt YAML behind it"
        )
        orphans.append((path, reason))
    return orphans


def find_drift() -> list[tuple[Path, str]]:
    """Compare expected vs on-disk content for every agent .md.

    Returns a list of (out_path, reason) for each file that diverges. Empty list
    means everything is in sync.
    """
    drift: list[tuple[Path, str]] = []
    for yaml_path in iter_prompt_yamls():
        out_path, expected = render_one(yaml_path)
        if not out_path.exists():
            drift.append((out_path, "missing"))
            continue
        actual = out_path.read_text(encoding="utf-8")
        if actual != expected:
            drift.append((out_path, "out of sync"))
    return drift


def sync_one(yaml_path: Path) -> Path:
    out_path, content = render_one(yaml_path)
    out_path.write_text(content, encoding="utf-8")
    return out_path


def ensure_synced() -> list[Path]:
    """Regenerate every agent .md from YAML. Idempotent and silent.

    Called from runtime entry points (`run_research.py`, `run_eval_claude_code.py`)
    before the Claude Agent SDK reads `.claude/agents/`. Returns the list of
    written paths so callers can log if they want.

    When `MLE_SOLVER_IS_REMOTE` is set explicitly (true|false), the unwanted
    mle-solver variant is removed from `.claude/agents/` so a previous run
    with the other setting cannot leave a stale .md visible to the manager.
    """
    AGENTS_DIR.mkdir(parents=True, exist_ok=True)
    is_remote = _is_remote_filter()
    if is_remote is True:
        (AGENTS_DIR / "mle-solver.md").unlink(missing_ok=True)
    elif is_remote is False:
        (AGENTS_DIR / "mle-solver-remote.md").unlink(missing_ok=True)
    return [sync_one(p) for p in iter_prompt_yamls()]


def cmd_sync() -> int:
    written = ensure_synced()
    for out in written:
        print(f"  {out.relative_to(PROJECT_DIR)}")
    print(f"\nSynced {len(written)} agent file(s) to {AGENTS_DIR.relative_to(PROJECT_DIR)}/")
    return 0


def cmd_check() -> int:
    drift = find_drift()
    orphans = check_orphans()
    if not drift and not orphans:
        count = len(iter_prompt_yamls())
        print(f"OK — all {count} agent .md files match their YAML source, no orphans.")
        return 0
    if drift:
        print(
            "DRIFT — these .claude/agents/*.md no longer match holosophos/holosophos/prompts/*.yaml:",
            file=sys.stderr,
        )
        for out_path, reason in drift:
            print(f"  {out_path.relative_to(PROJECT_DIR)}  ({reason})", file=sys.stderr)
        print("\nFix: run `python scripts/sync_claude_agents.py`.", file=sys.stderr)
    if orphans:
        print(
            "\nORPHANS — these .claude/agents/*.md would be loaded by the manager but "
            "no prompt YAML generates them:",
            file=sys.stderr,
        )
        for out_path, reason in orphans:
            print(f"  {out_path.relative_to(PROJECT_DIR)}  ({reason})", file=sys.stderr)
        print("\nFix: delete them, or add the prompt YAML they should come from.", file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else "")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify .md files are in sync with YAML; exit 1 on drift, do not write.",
    )
    args = parser.parse_args()
    return cmd_check() if args.check else cmd_sync()


if __name__ == "__main__":
    sys.exit(main())
